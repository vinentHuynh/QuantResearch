import assert from 'node:assert/strict';
import { chromium } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
import { strategyTitle } from '../shared/ts/formatting.ts';

const origin='http://127.0.0.1:8001';
const folder=`reports/testing-indicators-${new Date().toISOString().replaceAll(':','-')}`;
await mkdir(folder,{recursive:true});
const state=await(await fetch(origin+'/api/workbench/state?view=summary')).json();
const browser=await chromium.launch();
const page=await browser.newPage({viewport:{width:1500,height:1100}});
const errors=[];const checks=[];
page.on('pageerror',e=>errors.push(e.message));
try {
 await page.goto(origin+'/#/scripts',{waitUntil:'networkidle'});
 const name=strategyTitle(state.strategies.find(s=>s.id==='short-term-reversal-minute').name);
 const card=page.locator('section.wb-card').filter({has:page.getByRole('heading',{name,exact:true})});
 await card.getByText('Testing details',{exact:true}).click();
 await card.getByText('Most viable recorded run',{exact:true}).waitFor();
 assert.match(await card.innerText(),/6 succeeded/);
 assert.match(await card.innerText(),/4 recorded issues/);
 assert.match(await card.innerText(),/146,035/);
 assert.match(await card.innerText(),/Backtested/i);
 assert.match(await card.innerText(),/4 reviewed · 0 awaiting review/);
 assert.match(await card.innerText(),/Review completed/);
 assert.match(await card.innerText(),/declared six-case risk campaign fails/);
 await card.getByText('Failure reasons and evidence (4)',{exact:true}).click();
 assert.match(await card.innerText(),/20\.60%/);
 await card.scrollIntoViewIfNeeded();
 await page.screenshot({path:folder+'/scripts-testing.png'});
 await card.getByRole('button',{name:'Inspect most viable run',exact:true}).click();
 await page.getByRole('dialog').waitFor();
 assert.match(await page.getByRole('dialog').innerText(),/146,035/);
 await page.keyboard.press('Escape');
 checks.push('NQ minute card shows all six cases, four failures, numerical reasons and the correct linked five-minute candidate.');
 await page.getByRole('textbox',{name:'Testing evidence market',exact:true}).click();
 await page.getByRole('option',{name:'ES',exact:true}).click();
 await card.getByText('Not tested',{exact:true}).waitFor();
 assert.match(await card.innerText(),/No completed, positive, traded run/);
 await page.getByRole('textbox',{name:'Testing evidence market',exact:true}).click();
 await page.getByRole('option',{name:'NQ',exact:true}).click();
 await card.getByText('Backtested',{exact:true}).first().waitFor();
 checks.push('Market filtering excludes unrelated-market results and updates the candidate.');
 const dailyCard=page.locator('section.wb-card').filter({has:page.getByRole('heading',{name:strategyTitle(state.strategies.find(s=>s.id==='short-term-reversal').name),exact:true})});
 await dailyCard.getByText('Testing details',{exact:true}).click();
 await dailyCard.locator('summary').filter({hasText:'Failure reasons and evidence'}).click();
 await dailyCard.getByRole('button',{name:/Open evaluation/}).first().click();
 assert.match(page.url(),/#\/evaluations/);
 await page.getByRole('link',{name:'Scripts & library',exact:true}).click();
 checks.push('A numerical evaluation failure links directly to its evaluation page.');
 await page.getByRole('link',{name:'Library',exact:true}).click();
 await page.getByLabel('Search strategy library').fill('es_nq_strategies');
 const row=page.getByRole('row').filter({hasText:'scripts/es_nq/es_nq_strategies.py'});
 await row.getByText('Testing details',{exact:true}).first().click();
 assert(await row.getByText('Testing progress',{exact:true}).count()>0);
 assert(await row.getByText('Most viable recorded run',{exact:true}).count()>0);
 assert(await row.getByText(/Review completed/).count()>0);
 await page.screenshot({path:folder+'/library-testing.png'});
 await row.getByRole('button',{name:'Inspect scripts/es_nq/es_nq_strategies.py',exact:true}).click();
 await page.getByRole('dialog').getByText('Testing details',{exact:true}).first().click();
 await page.getByRole('dialog').getByText('Testing progress',{exact:true}).first().waitFor();
 await page.getByRole('dialog').getByText(/Review completed/).first().waitFor();
 await page.keyboard.press('Escape');
 await page.getByLabel('Search strategy library').fill('factor_ls');
 await page.getByText('Adapter required',{exact:true}).first().waitFor();
 checks.push('Library rows and source drawer show per-adapter evidence; unported sources show the adapter blocker.');
 await page.getByRole('link',{name:'Runnable scripts',exact:true}).click();
 await page.setViewportSize({width:390,height:844});
 await card.scrollIntoViewIfNeeded();
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+2);
 assert.equal(overflow,false,'Scripts page must not overflow on mobile');
 await page.screenshot({path:folder+'/scripts-mobile.png'});
 checks.push('Script cards fit a 390px viewport.');
 const fixture=structuredClone(state);
 const minuteRuns=fixture.runs.filter(r=>r.input.strategy.id==='short-term-reversal-minute');
 minuteRuns[0].status='Running';delete minuteRuns[0].result;
 minuteRuns[1].status='Queued';delete minuteRuns[1].result;
 await page.route('**/api/workbench/state?view=summary',route=>route.fulfill({json:fixture}));
 await page.goto(origin+'/#/scripts',{waitUntil:'networkidle'});
 await page.reload({waitUntil:'networkidle'});
 await card.getByText('Testing details',{exact:true}).click();
 await card.getByText('Testing in progress',{exact:true}).waitFor();
 assert.match(await card.innerText(),/4 succeeded · 1 running · 1 queued/);
 assert.match(await card.innerText(),/Recorded runs finished: 4 \/ 6/);
 await card.getByRole('progressbar',{name:'Recorded runs finished'}).waitFor();
 await card.scrollIntoViewIfNeeded();
 await page.screenshot({path:folder+'/progress-fixture.png'});
 checks.push('Read-only browser fixture verifies active progress, queued/running counts and completion denominator without launching runs.');
 assert.deepEqual(errors,[]);
 await writeFile(folder+'/validation.json',JSON.stringify({checks,errors},null,2));
 console.log(JSON.stringify({checks,errors},null,2));
} catch(e) { await page.screenshot({path:folder+'/failure.png',fullPage:true}); throw e; }
finally { await browser.close(); }
